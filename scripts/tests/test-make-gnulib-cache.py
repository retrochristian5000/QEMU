from __future__ import annotations

import importlib.util
import os
import pathlib
import shlex
import shutil
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
HELPER = ROOT / "scripts" / "ensure-make.py"


def run(*args: str, cwd=None) -> str:
    completed = subprocess.run(
        args,
        cwd=cwd,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if completed.returncode != 0:
        raise SystemExit(
            "error: command failed: "
            + " ".join(args)
            + ("\n" + completed.stderr if completed.stderr else "")
        )
    return completed.stdout.strip()


def main() -> int:
    git = shutil.which("git")
    if not git:
        raise SystemExit("error: git is required for GNU Make gnulib cache test")

    spec = importlib.util.spec_from_file_location("whp_ensure_make", HELPER)
    if spec is None or spec.loader is None:
        raise SystemExit("error: could not load scripts/ensure-make.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    with tempfile.TemporaryDirectory() as td:
        root = pathlib.Path(td)
        origin = root / "origin"
        build_root = root / "build"

        run(git, "init", str(origin))
        gnulib_tool = origin / "gnulib-tool"
        gnulib_tool.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
        gnulib_tool.chmod(0o755)
        run(git, "-C", str(origin), "add", "gnulib-tool")
        run(
            git, "-C", str(origin),
            "-c", "user.name=WHP test",
            "-c", "user.email=whp-test@example.invalid",
            "commit", "-m", "test gnulib seed",
        )
        revision = run(git, "-C", str(origin), "rev-parse", "HEAD")

        module.GNULIB_URL = str(origin)
        module.GNULIB_COMMIT = revision

        first = module.ensure_gnulib_cache(build_root, git)
        expected = build_root / "cache" / "gnulib" / revision
        if first != expected:
            raise SystemExit(
                f"error: gnulib cache path drifted: {first} != {expected}"
            )
        if not module.gnulib_cache_usable(first, git):
            raise SystemExit("error: freshly populated gnulib cache is unusable")

        # Remove the only source repository. Cache reuse must now be fully
        # local; any attempted fetch will fail this second call.
        shutil.rmtree(origin)
        second = module.ensure_gnulib_cache(build_root, git)
        if second != first:
            raise SystemExit("error: gnulib cache path changed on reuse")
        if not module.gnulib_cache_usable(second, git):
            raise SystemExit("error: reused gnulib cache became unusable")


    # A generated Autotools cache is complete only if autopoint's
    # gettext macro exists alongside configure and Makefile.in.
    with tempfile.TemporaryDirectory(prefix="whp-make-gettext-cache-") as td:
        generated = pathlib.Path(td)
        marker = "MAKE_GENERATED_SCHEMA=2\n"
        (generated / ".whp-make-generated").write_text(
            marker, encoding="utf-8"
        )
        for relative in (
            "configure", "Makefile.in", "lib/Makefile.in",
            "build.cfg.in", "src/config.h.in", "build.sh",
        ):
            item = generated / relative
            item.parent.mkdir(parents=True, exist_ok=True)
            item.write_text("test\n", encoding="utf-8")

        if module.generated_source_usable(generated, marker):
            raise SystemExit(
                "error: GNU Make accepted generated source missing gettext.m4"
            )
        macro = generated / "m4" / "gettext.m4"
        macro.parent.mkdir(parents=True)
        macro.write_text("dnl generated by autopoint\n", encoding="utf-8")
        if not module.generated_source_usable(generated, marker):
            raise SystemExit(
                "error: GNU Make rejected complete generated gettext source"
            )
        macro.unlink()
        if module.generated_source_usable(generated, marker):
            raise SystemExit(
                "error: GNU Make retained cache after gettext macro vanished"
            )

    with tempfile.TemporaryDirectory(prefix="whp-aclocal-path-") as td:
        root = pathlib.Path(td)
        primary = root / "macros"
        extra = root / "extra"
        primary.mkdir()
        extra.mkdir()
        expected = os.pathsep.join((str(primary), str(extra)))
        if module.validated_aclocal_path(str(primary), str(extra)) != expected:
            raise SystemExit("error: a valid macro path was not preserved")
        for invalid in (":/missing", str(root / "missing"), "relative/m4",
                        str(extra) + "\npoison", str(extra) + os.pathsep):
            try:
                module.validated_aclocal_path(str(primary), invalid)
            except RuntimeError as exc:
                if "ACLOCAL_PATH" not in str(exc):
                    raise
            else:
                raise SystemExit(
                    f"error: GNU Make accepted corrupt ACLOCAL_PATH: {invalid!r}"
                )

    # pkg.m4 is not always beside pkg-config: an executable may be a
    # wrapper or symlink, while Automake has its own authoritative macro
    # directory. Keep inherited path validation strict.
    with tempfile.TemporaryDirectory(prefix="whp-make-pkg-macro-") as td:
        root = pathlib.Path(td)
        pkg_prefix = root / "pkgconf-prefix"
        selected_pkg = pkg_prefix / "bin" / "pkg-config"
        selected_pkg.parent.mkdir(parents=True)
        selected_pkg.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
        selected_pkg.chmod(0o755)
        adjacent = pkg_prefix / "share" / "aclocal"
        adjacent.mkdir(parents=True)
        (adjacent / "pkg.m4").write_text("dnl pkgconf macro\n", encoding="utf-8")
        found = module.pkg_config_aclocal_dir(str(selected_pkg))
        if found != str(adjacent):
            raise SystemExit("error: adjacent pkg-config macros were missed")

        wrapper = root / "wrappers" / "pkg-config"
        wrapper.parent.mkdir()
        wrapper.symlink_to(selected_pkg)
        found = module.pkg_config_aclocal_dir(str(wrapper))
        if found != str(adjacent):
            raise SystemExit("error: symlinked pkg-config macros were missed")

        (adjacent / "pkg.m4").unlink()
        custom = root / "separately installed macros"
        custom.mkdir()
        (custom / "pkg.m4").write_text("dnl independent pkg.m4\n", encoding="utf-8")
        found = module.pkg_config_aclocal_dir(
            str(wrapper), inherited=str(custom)
        )
        if found != str(custom):
            raise SystemExit("error: valid ACLOCAL_PATH macro was missed")
        module.validated_aclocal_path(found, str(custom))
        if module.pkg_config_aclocal_dir(
            str(wrapper), inherited=str(root / "missing") + os.pathsep + str(custom)
        ) != str(custom):
            raise SystemExit("error: pkg.m4 was not discoverable from a valid entry")
        try:
            module.validated_aclocal_path(str(custom), str(root / "missing"))
        except RuntimeError:
            pass
        else:
            raise SystemExit("error: inherited missing ACLOCAL_PATH became accepted")

        default = root / "automake system macros"
        default.mkdir()
        (default / "pkg.m4").write_text("dnl Automake macro\n", encoding="utf-8")
        aclocal = root / "aclocal"
        aclocal.write_text(
            "#!/bin/sh\nprintf '%s\\n' " + shlex.quote(str(default)) + "\n",
            encoding="utf-8",
        )
        aclocal.chmod(0o755)
        found = module.pkg_config_aclocal_dir(
            str(wrapper), aclocal=str(aclocal)
        )
        if found != str(default):
            raise SystemExit("error: selected aclocal macro directory was missed")

        (default / "pkg.m4").unlink()
        try:
            module.pkg_config_aclocal_dir(str(wrapper), aclocal=str(aclocal))
        except RuntimeError as exc:
            if "pkg.m4 is unavailable" not in str(exc):
                raise
        else:
            raise SystemExit("error: missing pkg.m4 was silently accepted")

    print("GNU Make gnulib cache reuse: verified")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
