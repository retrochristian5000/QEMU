/* Check the unsigned ENTER imm16 allocation on a 32-bit stack. */
__asm__(
    ".text\n"
    ".globl _start\n"
    "_start:\n"
    "movl %esp, %edx\n"
    "leal scratch+65552, %esp\n"
    ".macro check_enter count, level=0\n"
    "movl %esp, %ecx\n"
    "movl %esp, %ebp\n"
    "enter $\\count, $\\level\n"
    "movl %ecx, %eax\n"
    "subl %esp, %eax\n"
    "cmpl $(\\count+4+4*(\\level & 31)), %eax\n"
    "jne 1f\n"
    "leave\n"
    "cmpl %ecx, %esp\n"
    "jne 1f\n"
    ".endm\n"
    "check_enter 0\n"
    "check_enter 0x7fff\n"
    "check_enter 0x8000\n"
    "check_enter 0xffff\n"
    "check_enter 0x8000, 1\n"
    "check_enter 0x8000, 33\n"
    "xorl %ebx, %ebx\n"
    "jmp 2f\n"
    "1: movl $1, %ebx\n"
    "2: movl %edx, %esp\n"
    "movl $1, %eax\n"
    "int $0x80\n"
    ".bss\n"
    ".balign 16\n"
    "scratch: .skip 131072\n"
);
